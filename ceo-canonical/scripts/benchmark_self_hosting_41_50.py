from __future__ import annotations

import json
import shutil
import tempfile
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from ceo_core.models import ProjectState
from ceo_core.self_hosting_alpha import (
    AutoPromotionGuard, CandidateBuildGenerator, FirstExerciseEvaluator, HumanPromotionGate,
    SelfHostingAlphaGate, SelfHostingReleaseDiff, UpdateRollbackManager,
)
from ceo_core.self_hosting_evolution import SelfImprovementAcceptanceGate
from ceo_core.self_hosting_tools import SelfHostingWorkspace

OUT = ROOT / "reports" / "SELF_HOSTING_41_50_BENCHMARK.json"


def main() -> int:
    with tempfile.TemporaryDirectory(prefix="ceo-self-41-50-") as td:
        temp = Path(td)
        stable = temp / "stable"
        shutil.copytree(ROOT, stable, ignore=shutil.ignore_patterns(".git", "__pycache__", ".pytest_cache", "data", "browser_profiles", "reports"))
        state = ProjectState(goal="Prepare CEO Self-Hosting Alpha safely")
        manager = SelfHostingWorkspace(stable, temp / "candidates")
        ws = manager.create(state, label="alpha")
        candidate = Path(ws["candidate_root"])
        mission_id = "alpha-dogfood-41-50"
        state.metadata.setdefault(SelfImprovementAcceptanceGate.KEY, {})[mission_id] = {
            "mission_id": mission_id,
            "stage": "ELIGIBLE_FOR_PROMOTION",
            "auto_promoted": False,
            "promotion_requires_human": True,
        }
        # Real candidate change in a copy of CEO, never stable.
        marker = candidate / "SELF_HOSTING_ALPHA_CANDIDATE.txt"
        marker.write_text("candidate build generated by CEO self-hosting benchmark\n", encoding="utf-8")

        guard = AutoPromotionGuard(); guard.initialize(state)
        agent_blocked = False
        try:
            guard.assert_manual(state, human_confirmed=True, actor="agent")
        except PermissionError:
            agent_blocked = True

        diff = SelfHostingReleaseDiff().compare(state, stable, candidate, mission_id=mission_id)
        build = CandidateBuildGenerator().build(state, candidate, temp / "builds", mission_id=mission_id, version="1.1.0-dev5", running_root=stable)
        rollback = UpdateRollbackManager().prepare(state, stable, temp / "rollback", version="1.1.0-dev4")
        restored = UpdateRollbackManager().restore_to_staging(rollback["package"], temp / "rollback-restored", expected_sha256=rollback["sha256"])
        human = HumanPromotionGate().decide(state, mission_id=mission_id, decision="APPROVE", human_confirmed=True, actor="human", note="benchmark only; do not install")

        ev = FirstExerciseEvaluator()
        chrome = ev.chrome(state, field_executed=False, success=True, evidence=["harness-simulation"], details={"opened":True,"navigated":True,"read_content":True,"evidence_returned":True}, platform="linux-harness")
        multi = ev.multi_app(state, field_executed=False, success=True, evidence=["harness-simulation"], details={"browser_step":True,"artifact_step":True,"terminal_step":True,"result_registered":True}, platform="linux-harness")
        chatgpt = ev.chatgpt(state, field_executed=False, success=True, evidence=["harness-simulation"], details={"task_assigned":True,"response_processed":True})
        self_host = ev.self_hosting(state, field_executed=True, success=True, evidence=[str(build["package"]), str(marker)], mission_id=mission_id, details={"stable_unchanged": manager.immutable.verify(state)["unchanged"]})
        alpha = SelfHostingAlphaGate().assess(state)

        result = {
            "benchmark": "self_hosting_41_50_release_and_alpha_gate",
            "pass": bool(
                agent_blocked
                and diff["changed_count"] >= 1
                and Path(build["package"]).is_file()
                and Path(rollback["package"]).is_file()
                and restored["running_process_replaced"] is False
                and human["installation_performed"] is False
                and self_host["verified"] is True
                and chrome["status"] == "NOT_VERIFIED"
                and multi["status"] == "NOT_VERIFIED"
                and chatgpt["status"] == "NOT_VERIFIED"
                and alpha["ready"] is False
                and manager.immutable.verify(state)["unchanged"] is True
            ),
            "auto_promotion_agent_blocked": agent_blocked,
            "release_diff": {k: diff[k] for k in ("added","modified","removed","changed_count")},
            "candidate_build": {k: build[k] for k in ("package_sha256","file_count","installed","auto_promoted")},
            "human_promotion_decision": {k: human[k] for k in ("decision","approved","installation_performed")},
            "rollback": {"prepared": Path(rollback["package"]).is_file(), "restored_to_staging": restored["ok"], "running_process_replaced": restored["running_process_replaced"]},
            "field_exercises": {"chrome": chrome["status"], "multi_app": multi["status"], "chatgpt": chatgpt["status"], "self_hosting": self_host["status"]},
            "alpha_gate": {"status": alpha["status"], "ready": alpha["ready"], "blockers": alpha["blockers"]},
            "stable_unchanged": manager.immutable.verify(state)["unchanged"],
            "windows_physical": "DEFERRED_BY_USER",
            "live_provider": "NOT_VERIFIED",
            "production_verified": False,
        }
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(json.dumps(result, indent=2, sort_keys=True), encoding="utf-8")
        print(json.dumps(result, indent=2, sort_keys=True))
        return 0 if result["pass"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
